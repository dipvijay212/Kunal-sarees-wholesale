/* Builders ----------------------------------------------------------------- */

function buildImages({ name, fabric, photoIds }: ProductSeed): ProductImage[] {
  const [drape, fabricDetail, borderDetail] = photoIds;
  return [
    unsplashImage(drape, `${name} draped on a model`),
    unsplashImage(fabricDetail, `${name} — ${fabric.toLowerCase()} fabric detail`),
    unsplashImage(borderDetail, `${name} — border and pallu detail`),
  ];
}

/** Initials used as the colour suffix in a variant code, e.g. "Deep Wine" → "DW". */
function colorSuffix(colorName: string): string {
  const initials = colorName
    .split(/\s+/)
    .map((word) => word[0])
    .join("");
  return (initials.length >= 2 ? initials : colorName.slice(0, 2)).slice(0, 2).toUpperCase();
}

/** Splits product stock evenly across colourways, giving the remainder to the first. */
function buildVariants({ id, productCode, colors, stock }: ProductSeed): ProductVariant[] {
  const perColor = Math.floor(stock / colors.length);
  const remainder = stock - perColor * colors.length;

  return colors.map((color, index) => ({
    id: `${id}-v${index + 1}`,
    productId: id,
    variantCode: `${productCode}-${colorSuffix(color.name)}`,
    color,
    stock: perColor + (index === 0 ? remainder : 0),
  }));
}

export const products: Product[] = seeds.map((seed) => {
  const { photoIds, ...product } = seed;
  return { ...product, images: buildImages(seed), variants: buildVariants(seed) };
});
